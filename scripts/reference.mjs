// Generates docs/REFERENCE.md: every public export, one line each, grouped by
// module in the order src/index.ts lists them. The line is the first sentence
// of the export's doc comment (or the comment directly above it).
//
//   node scripts/reference.mjs          write docs/REFERENCE.md
//   import { render } from ...          scripts/docs.test.ts compares render() to the file
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function firstSentence(text) {
  const flat = text.replace(/\s+/g, " ").trim();
  const m = flat.match(/^(.*?[.!?])(\s|$)/);
  return (m ? m[1] : flat).replace(/\|/g, "\\|");
}

function docAbove(lines, i) {
  const out = [];
  let j = i - 1;
  if (lines[j]?.trim().endsWith("*/")) {
    while (j >= 0 && !lines[j].trim().startsWith("/**")) out.unshift(lines[j--]);
    out.unshift(lines[j] ?? "");
    return out.map((l) => l.replace(/^\s*\/?\*+\/?\s?/, "").replace(/\*\/\s*$/, "")).join(" ");
  }
  while (j >= 0 && lines[j].trim().startsWith("//")) out.unshift(lines[j--].replace(/^\s*\/\/\s?/, ""));
  return out.join(" ");
}

export function render() {
  const index = readFileSync(path.join(ROOT, "src/index.ts"), "utf8");
  const mods = [...index.matchAll(/export \* from "\.\/([^"]+)";/g)].map((m) => m[1]);
  let out = "# Reference\n\n<!-- Generated by `bun run reference`. Do not edit by hand. -->\n\n";
  out += "Everything below is exported from `site-world`. One line each; read the source for the rest.\n";
  let group = "";
  for (const mod of mods) {
    const dir = mod.split("/")[0];
    if (dir !== group) {
      group = dir;
      out += `\n## ${dir}/\n`;
    }
    const file = ["ts", "tsx"].map((e) => `src/${mod}.${e}`).find((f) => {
      try { readFileSync(path.join(ROOT, f)); return true; } catch { return false; }
    });
    const lines = readFileSync(path.join(ROOT, file), "utf8").split("\n");
    const rows = [];
    lines.forEach((line, i) => {
      const m = line.match(/^export (?:declare )?(?:async )?(const|function|class|interface|type|let)\s+(\w+)/);
      if (!m) return;
      rows.push(`| \`${m[2]}\` | ${m[1]} | ${firstSentence(docAbove(lines, i))} |`);
    });
    if (rows.length === 0) continue;
    out += `\n### \`${mod}\`\n\n| Export | Kind | What |\n| --- | --- | --- |\n${rows.join("\n")}\n`;
  }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(ROOT, "docs/REFERENCE.md"), render());
  console.log("wrote docs/REFERENCE.md");
}
